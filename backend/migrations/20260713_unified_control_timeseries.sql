SELECT tenant_id, id, 'thermostat', 'air_conditioner_thermostat', true, created_at, updated_at
FROM devices
WHERE is_thermostat = true
ON CONFLICT (device_id, module_type) DO UPDATE SET
  tenant_id = EXCLUDED.tenant_id,
  is_active = true,
  updated_at = EXCLUDED.updated_at;

COMMIT;
